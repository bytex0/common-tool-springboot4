package io.github.bytex0.desensitize.enums;

/**
 * 脱敏类型(DesensitizeType)内置策略
 *
 * @author bytex0
 * @since 2026-10-05 15:57:28
 */
public enum DesensitizeType {

    /**
     * 11 位手机号保留前三后四位；非法输入全部遮蔽。
     */
    PHONE,

    /**
     * 邮箱保留首个本地码点和域，使用固定四星；单字本地名也遮蔽。
     */
    EMAIL,

    /**
     * 两字姓名隐藏末字，多字姓名保留首尾；单字姓名全部遮蔽。
     */
    NAME,

    /**
     * 合法长度身份证保留首末四位，中间按实际码点数量替换。
     */
    ID_CARD,

    /**
     * 数字银行卡保留首末四位，中间固定四星。
     */
    BANK_CARD,

    /**
     * 地址保留前六后两码点，中间固定四星；短地址全部遮蔽。
     */
    ADDRESS,

    /**
     * 密码固定输出六星，不暴露原始长度。
     */
    PASSWORD,

    /**
     * 车牌保留前两码点和末位，中间固定四星。
     */
    CAR_NUMBER,

    /**
     * 固话保留区号和末四位，支持区号与号码之间的连字符。
     */
    FIXED_PHONE,

    /**
     * IPv4 保留首末段和可选端口，中间两段隐藏。
     */
    IPV4,

    /**
     * IPv6 字面值校验后保留首个显式段；无显式前缀时全部遮蔽。
     */
    IPV6,

    /**
     * 护照保留前后两码点，中间固定四星。
     */
    PASSPORT,

    /**
     * 军官证保留前后两码点，中间固定四星，短值全部遮蔽。
     */
    MILITARY_ID,

    /**
     * 十二位数字联行号保留首末四位，中间固定四星。
     */
    CNAPS_CODE,

    /**
     * 非空文本固定输出六星，保留旧全遮蔽策略格式。
     */
    MASK_ALL,

    /**
     * 使用注解指定的 Spring Bean 或公开无参处理器，也支持工厂显式注册后按类型调用。
     */
    CUSTOM,

    /**
     * 隐藏域名首段，保留其他域和可选端口；IP 域名采用 IP 规则。
     */
    DOMAIN
}
